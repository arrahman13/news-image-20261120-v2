#!/usr/bin/env python3
"""
Entrypoint for the make.fun kit run.

The entry image is generated by build_image.py and committed as entry.png.
This entrypoint reproduces it byte-identically by copying the committed
entry.png into the output directory ($MAKEFUN_OUTPUT_DIR/entry.png, or
./output/entry.png when the variable is unset).
"""

import os
import shutil


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "entry.png")
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or os.path.join(os.getcwd(), "output")
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "entry.png")
    shutil.copyfile(src, dst)
    print("entry.png ->", dst)


if __name__ == "__main__":
    main()
